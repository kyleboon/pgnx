// Command genmagic finds the magic multipliers behind the chess
// package's slider attack tables (magic.go) and writes them as a Go
// source file. It is run by go generate from the chess package; the
// search is seeded, so the output is reproducible, and the chess
// package's TestSliderAttacksEverySubset verifies the committed
// constants against every occupancy subset.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math/bits"
	"os"
)

var (
	rookDirs   = [][2]int{{1, 0}, {-1, 0}, {0, 1}, {0, -1}}
	bishopDirs = [][2]int{{1, 1}, {1, -1}, {-1, 1}, {-1, -1}}
)

func main() {
	out := flag.String("o", "magic_table.go", "output file")
	flag.Parse()

	seed := xorshift(0x9E3779B97F4A7C15)
	rng := &seed
	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./internal/genmagic; DO NOT EDIT.\n\n")
	buf.WriteString("package chess\n\n")
	buf.WriteString("// Magic multipliers for the slider attack tables, one per square (a1\n")
	buf.WriteString("// first): see magic.go.\n")
	writeTable(&buf, "rookMagicNumbers", rookDirs, rng)
	buf.WriteString("\n")
	writeTable(&buf, "bishopMagicNumbers", bishopDirs, rng)
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func writeTable(buf *bytes.Buffer, name string, dirs [][2]int, rng *xorshift) {
	fmt.Fprintf(buf, "var %s = [64]uint64{\n", name)
	for s := 0; s < 64; s++ {
		fmt.Fprintf(buf, "\t%#016x,\n", findMagic(s, dirs, rng))
	}
	buf.WriteString("}\n")
}

// findMagic searches sparse random multipliers until one maps every
// subset of s's relevant mask to a slot holding only its own attack set.
func findMagic(s int, dirs [][2]int, rng *xorshift) uint64 {
	mask := relevantMask(s, dirs)
	n := bits.OnesCount64(mask)
	shift := uint(64 - n)
	size := 1 << uint(n)
	occs := make([]uint64, 0, size)
	refs := make([]uint64, 0, size)
	for occ := uint64(0); ; occ = (occ - mask) & mask {
		occs = append(occs, occ)
		refs = append(refs, slideAttacks(s, dirs, occ))
		if (occ-mask)&mask == 0 {
			break
		}
	}
	used := make([]uint64, size)
	epoch := make([]uint32, size)
	for try := uint32(1); ; try++ {
		m := rng.next() & rng.next() & rng.next()
		if bits.OnesCount64((mask*m)&0xFF00000000000000) < 6 {
			continue
		}
		ok := true
		for i, occ := range occs {
			idx := (occ * m) >> shift
			if epoch[idx] == try && used[idx] != refs[i] {
				ok = false
				break
			}
			epoch[idx], used[idx] = try, refs[i]
		}
		if ok {
			return m
		}
	}
}

func relevantMask(s int, dirs [][2]int) uint64 {
	const fileA, rank1 uint64 = 0x0101010101010101, 0xFF
	edges := (fileA|fileA<<7)&^(fileA<<uint(s&7)) | (rank1|rank1<<56)&^(rank1<<uint(8*(s>>3)))
	return slideAttacks(s, dirs, 0) &^ edges
}

func slideAttacks(s int, dirs [][2]int, occ uint64) uint64 {
	var m uint64
	file, rank := s&7, s>>3
	for _, d := range dirs {
		f, r := file+d[0], rank+d[1]
		for f >= 0 && f < 8 && r >= 0 && r < 8 {
			to := uint64(1) << uint(r<<3|f)
			m |= to
			if occ&to != 0 {
				break
			}
			f, r = f+d[0], r+d[1]
		}
	}
	return m
}

// xorshift is a fixed-seed xorshift64* generator, so a rerun reproduces
// the committed table.
type xorshift uint64

func (x *xorshift) next() uint64 {
	v := uint64(*x)
	v ^= v >> 12
	v ^= v << 25
	v ^= v >> 27
	*x = xorshift(v)
	return v * 2685821657736338717
}
